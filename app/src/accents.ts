function casse(mot: string, remplacement: string): string {
  if (mot.length > 1 && mot === mot.toUpperCase()) return remplacement.toUpperCase();
  return mot.charAt(0) === mot.charAt(0).toUpperCase()
    ? remplacement.charAt(0).toUpperCase() + remplacement.slice(1)
    : remplacement;
}

/** Pose les accents francais sur un texte destine a l'affichage. */
export function accentue(texte: string): string {
  const mots = texte.replace(/[A-Za-z]+/g, (mot) => {
    const remplacement = MOTS[mot.toLowerCase()];
    return remplacement === undefined ? mot : casse(mot, remplacement);
  });
  const apostrophes = mots.replace(
    /\b([ldnsjmc]|qu) (?=[aeiouyàâäéèêëîïôöùûü])/gi,
    (_m, lettre: string) => `${lettre}'`,
  );
  return apostrophes.replace(/\b([aA]) (la|le|les|l['’])/g, (_m, a: string, article: string) => {
    return `${a === 'A' ? 'À' : 'à'} ${article}`;
  });
}

/** `notationHtml` apres accentuation du texte source. */
export function notationHtml(texte: string): string {
  return notationHtmlCommun(accentue(texte));
}

/** `notationTexte` apres accentuation du texte source. */
export function notationTexte(texte: string): string {
  return notationTexteCommun(accentue(texte));
}
